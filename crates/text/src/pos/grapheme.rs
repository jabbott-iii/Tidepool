//! Extended grapheme cluster boundaries, as UAX #29 revision 47 defines them
//! for Unicode 17.0.0 (ADR-0018), on a `&str` and on a [`Rope`].
//!
//! A boundary is a byte offset between two user-perceived characters. Byte 0
//! and the length are boundaries, also of the empty text; an offset that is
//! not a char boundary, or is past the end, is not one. Every query takes any
//! `usize` and never panics. On a rope, chunk seams make no difference.
//!
//! ```
//! use tidepool_text::Rope;
//! use tidepool_text::pos::grapheme;
//!
//! let text = "e\u{301}🇺🇸!";
//! let clusters: Vec<&str> = grapheme::graphemes(text).collect();
//! assert_eq!(clusters, ["e\u{301}", "🇺🇸", "!"]);
//! assert!(!grapheme::is_boundary(text, 1));
//! assert_eq!(grapheme::next_boundary(text, 0), Some(3));
//! assert_eq!(grapheme::prev_boundary(text, 12), Some(11));
//!
//! let rope = Rope::from(text);
//! let spans: Vec<_> = rope.graphemes_in(0..rope.len())?.collect();
//! assert_eq!(spans, [0..3, 3..11, 11..12]);
//! # Ok::<(), tidepool_text::TextError>(())
//! ```
//!
//! # How it works
//!
//! Each char has three properties, packed into one byte by a table that
//! `cargo xtask ucd` generates: `Grapheme_Cluster_Break`,
//! `Indic_Conjunct_Break` and `Extended_Pictographic`. Rules GB3-GB9b
//! decide a boundary from the two chars around it. GB9c, GB11, GB12 and GB13
//! also look further back. A small state, stepped on every char and never
//! reset at a boundary, recognises exactly their left contexts. It has one
//! part for each rule's pattern, and the parts step independently:
//!
//! - GB9c: an InCB consonant, then InCB Linker and Extend chars, at least
//!   one of them a linker;
//! - GB11: a pictograph, then Extend chars, then a ZWJ;
//! - GB12 and GB13: a run of regional indicators, of which only the parity
//!   counts.
//!
//! [`graphemes`], and [`Rope::graphemes_in`] from byte 0, step the state
//! from the start of the text. A query needs the state only where a context
//! rule could apply, and there it steps back: one backward pass from the
//! position reads each part's pattern until the pattern ends, and stops
//! when all three have ended, or at the start of the text.
//! [`Rope::graphemes_in`] from a later byte steps back once, at the first
//! such position, and steps the state on from there.
//!
//! # Cost
//!
//! The costs count chars read. On a rope, add O(log n) to find the
//! position, once per query and once more for each step back.
//!
//! - Typical text: O(1) per query, and O(1) per char when iterating.
//! - A run of extending marks: O(1) per position, because GB9 joins a mark
//!   without looking back. A [`Rope::graphemes_in`] window inside the run
//!   costs only the window.
//! - Before a consonant (GB9c), or before a pictograph after a ZWJ (GB11):
//!   the step back is linear in the run of extending chars
//!   (`Grapheme_Cluster_Break` Extend or ZWJ) just before the position.
//! - Between two regional indicators (GB12 and GB13): the step back is
//!   linear in the run of regional indicators before the position. So
//!   repeated [`next_boundary`] or [`prev_boundary`] calls across one run of
//!   r indicators cost O(r²) in total. To sweep, use [`graphemes`] or
//!   [`Rope::graphemes_in`], which stay O(1) per char.
//! - [`next_boundary`] and [`prev_boundary`] read char by char up to the
//!   boundary they return, so inside one long cluster they are linear in
//!   the distance to its end or its start. Add a step back for each context
//!   rule they pass; `next_boundary` steps back at most once.
//! - An iterator steps back at most once, at the first context rule it
//!   meets, and never if it starts at byte 0.
//!
//! The step back never crosses a line break, because CR and LF end every
//! pattern.

