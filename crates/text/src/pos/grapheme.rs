// The rules.

/// What the two chars around a position say about it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Pair {
    /// A boundary, whatever came before.
    Break,
    /// No boundary, whatever came before.
    Join,
    /// GB9c, GB11 or GB12/13 may join; the state before the position
    /// decides.
    Context,
}

/// The left context of a position, for the rules that look back further
/// than one char. Each part recognises one pattern at the end of the text
/// before the position.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct State {
    /// GB12/13: the text ends in an odd number of regional indicators,
    /// preceded by the start of the text or by something else.
    ri_odd: bool,
    /// GB11: how much of `ExtPict Extend* ZWJ` the text ends in.
    emoji: Emoji,
    /// GB9c: how much of `Consonant [Extend Linker]* Linker [Extend
    /// Linker]*` (InCB values) the text ends in.
    conjunct: Conjunct,
}

/// The GB11 part of [`State`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Emoji {
    /// Not at the end of `ExtPict Extend*`.
    None,
    /// At the end of `ExtPict Extend*`.
    Pict,
    /// At the end of `ExtPict Extend* ZWJ`.
    PictZwj,
}

/// The GB9c part of [`State`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Conjunct {
    /// Not at the end of `Consonant [Extend Linker]*`.
    None,
    /// At the end of `Consonant Extend*`.
    Consonant,
    /// At the end of `Consonant [Extend Linker]* Linker [Extend Linker]*`.
    Linked,
}

/// The state at the start of the text (sot).
const START: State = State {
    ri_odd: false,
    emoji: Emoji::None,
    conjunct: Conjunct::None,
};

/// The state after one more char, of properties `p`.
const fn step(state: State, p: u8) -> State {
    let pict = matches!(state.emoji, Emoji::Pict);
    State {
        ri_odd: gcb(p) == REGIONAL_INDICATOR && !state.ri_odd,
        emoji: if ext_pict(p) || (gcb(p) == EXTEND && pict) {
            Emoji::Pict
        } else if gcb(p) == ZWJ && pict {
            Emoji::PictZwj
        } else {
            Emoji::None
        },
        conjunct: match incb(p) {
            INCB_CONSONANT => Conjunct::Consonant,
            INCB_LINKER => match state.conjunct {
                Conjunct::None => Conjunct::None,
                Conjunct::Consonant | Conjunct::Linked => Conjunct::Linked,
            },
            INCB_EXTEND => state.conjunct,
            _ => Conjunct::None,
        },
    }
}

/// The state after a text, recovered from the packed properties of its
/// chars read backward, from the last one; the start of the text ends
/// `before`. The three parts of the state step independently, so each is
/// recovered from its own pattern at the end of the text, as [`step`]
/// defines it. `before` is read only until all three patterns have ended.
fn recover(before: impl IntoIterator<Item = u8>) -> State {
    // Each part is `None` until its pattern has ended.
    let mut ri_odd = None;
    let mut emoji = None;
    let mut conjunct = None;
    // GB12/13: the parity of the regional indicators read so far.
    let mut odd = false;
    // GB11: once the last char has been read and was an Extend or a ZWJ,
    // whether it was a ZWJ. Extend chars before it are skipped.
    let mut after: Option<bool> = None;
    // GB9c: whether an InCB Linker has been read.
    let mut linker = false;
    for p in before {
        if ri_odd.is_none() {
            if gcb(p) == REGIONAL_INDICATOR {
                odd = !odd;
            } else {
                ri_odd = Some(odd);
            }
        }
        if emoji.is_none() {
            // As in `step`, Extended_Pictographic comes first.
            if ext_pict(p) {
                emoji = Some(if after == Some(true) {
                    Emoji::PictZwj
                } else {
                    Emoji::Pict
                });
            } else if gcb(p) == EXTEND {
                after.get_or_insert(false);
            } else if gcb(p) == ZWJ && after.is_none() {
                after = Some(true);
            } else {
                emoji = Some(Emoji::None);
            }
        }
        if conjunct.is_none() {
            match incb(p) {
                INCB_LINKER => linker = true,
                INCB_EXTEND => {}
                INCB_CONSONANT if linker => conjunct = Some(Conjunct::Linked),
                INCB_CONSONANT => conjunct = Some(Conjunct::Consonant),
                _ => conjunct = Some(Conjunct::None),
            }
        }
        if ri_odd.is_some() && emoji.is_some() && conjunct.is_some() {
            break;
        }
    }
    // At the start of the text, as from `START`: the run's parity, no
    // pictograph and no consonant.
    State {
        ri_odd: ri_odd.unwrap_or(odd),
        emoji: emoji.unwrap_or(Emoji::None),
        conjunct: conjunct.unwrap_or(Conjunct::None),
    }
}

/// Rules GB3-GB999, in order, for chars of properties `a` then `b`, as far
/// as the two chars alone decide them.
fn pair(a: u8, b: u8) -> Pair {
    match (gcb(a), gcb(b)) {
        // GB3.
        (CR, LF) => Pair::Join,
        // GB4 and GB5.
        (CONTROL | CR | LF, _) | (_, CONTROL | CR | LF) => Pair::Break,
        // GB6, GB7 and GB8.
        (L, L | V | LV | LVT) | (LV | V, V | T) | (LVT | T, T) => Pair::Join,
        // GB9, GB9a and GB9b.
        (_, EXTEND | ZWJ | SPACING_MARK) | (PREPEND, _) => Pair::Join,
        // GB12 and GB13.
        (REGIONAL_INDICATOR, REGIONAL_INDICATOR) => Pair::Context,
        // GB11.
        (ZWJ, _) if ext_pict(b) => Pair::Context,
        // GB9c.
        _ if incb(b) == INCB_CONSONANT && matches!(incb(a), INCB_LINKER | INCB_EXTEND) => {
            Pair::Context
        }
        // GB999.
        _ => Pair::Break,
    }
}

/// Whether GB9c, GB11 or GB12/13 joins `a` and `b`, given the state after
/// `a`. All three are joining rules and come before GB999, so their order
/// does not matter.
const fn context_joins(state: State, a: u8, b: u8) -> bool {
    (incb(b) == INCB_CONSONANT && matches!(state.conjunct, Conjunct::Linked))
        || (ext_pict(b) && matches!(state.emoji, Emoji::PictZwj))
        || (gcb(a) == REGIONAL_INDICATOR && gcb(b) == REGIONAL_INDICATOR && state.ri_odd)
}

