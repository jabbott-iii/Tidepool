/// Counts the chars the engine reads, in unit tests, so that they can show
/// how much work each query does.
#[cfg(test)]
pub(crate) mod work {
    use std::cell::Cell;

    thread_local! {
        static CHARS: Cell<u64> = const { Cell::new(0) };
    }

    /// The chars read on this thread so far.
    pub(crate) fn read() -> u64 {
        CHARS.with(Cell::get)
    }

    pub(super) fn add(chars: u64) {
        CHARS.with(|count| count.set(count.get() + chars));
    }
}

/// Counts `chars` chars read by the engine (unit tests only).
fn work(chars: u64) {
    #[cfg(test)]
    work::add(chars);
    #[cfg(not(test))]
    let _ = chars;
}

/// A text the engine reads: a `str` or a [`Rope`]. Offsets are byte
/// offsets from the start of the text.
trait Source {
    /// The length in bytes.
    fn len(&self) -> usize;

    /// Whether `byte` is a char boundary in `0..=len`.
    fn is_char_boundary(&self, byte: usize) -> bool;

    /// The largest char boundary at or before `byte`; `len` past the end.
    fn floor_char_boundary(&self, byte: usize) -> usize;

    /// The chars before the char boundary `byte`, with their offsets, from
    /// the nearest one back.
    fn chars_before(&self, byte: usize) -> impl Iterator<Item = (usize, char)>;

    /// The chars from the char boundary `byte` to the end, with their
    /// offsets.
    fn chars_from(&self, byte: usize) -> impl Iterator<Item = (usize, char)>;
}

impl Source for str {
    fn len(&self) -> usize {
        str::len(self)
    }

    fn is_char_boundary(&self, byte: usize) -> bool {
        str::is_char_boundary(self, byte)
    }

    fn floor_char_boundary(&self, byte: usize) -> usize {
        str::floor_char_boundary(self, byte)
    }

    fn chars_before(&self, byte: usize) -> impl Iterator<Item = (usize, char)> {
        self.get(..byte).unwrap_or_default().char_indices().rev()
    }

    fn chars_from(&self, byte: usize) -> impl Iterator<Item = (usize, char)> {
        let rest = self.get(byte..).unwrap_or_default();
        rest.char_indices().map(move |(at, c)| (byte + at, c))
    }
}

impl Source for Rope {
    fn len(&self) -> usize {
        Rope::len(self)
    }

    fn is_char_boundary(&self, byte: usize) -> bool {
        Rope::is_char_boundary(self, byte)
    }

    fn floor_char_boundary(&self, byte: usize) -> usize {
        Rope::floor_char_boundary(self, byte)
    }

    fn chars_before(&self, byte: usize) -> impl Iterator<Item = (usize, char)> {
        self.char_indices_in(0..byte)
            .ok()
            .into_iter()
            .flatten()
            .rev()
    }

    fn chars_from(&self, byte: usize) -> impl Iterator<Item = (usize, char)> {
        self.char_indices_in(byte..Rope::len(self))
            .ok()
            .into_iter()
            .flatten()
    }
}

/// The state of `src` before the char boundary `byte`, recovered by one
/// backward pass (see [`recover`]). It reads the chars before `byte` until
/// the longest of the three patterns ends: the run of regional indicators,
/// the char before `byte` and, if that is an Extend or a ZWJ, the Extend
/// chars before it, and the run of InCB Linker and Extend chars. A CR or LF
/// ends all three.
fn state_at<S: Source + ?Sized>(src: &S, byte: usize) -> State {
    recover(src.chars_before(byte).map(|(_, c)| {
        work(1);
        props(c)
    }))
}

/// Whether the char boundary `byte`, strictly inside `src`, is a boundary
/// between `a` and `b`, the properties of the chars around it.
fn breaks_at<S: Source + ?Sized>(src: &S, byte: usize, a: u8, b: u8) -> bool {
    match pair(a, b) {
        Pair::Break => true,
        Pair::Join => false,
        Pair::Context => !context_joins(state_at(src, byte), a, b),
    }
}

fn is_boundary_of<S: Source + ?Sized>(src: &S, byte: usize) -> bool {
    let len = src.len();
    if byte == 0 || byte == len {
        return true;
    }
    if byte > len || !src.is_char_boundary(byte) {
        return false;
    }
    let before = src.chars_before(byte).next();
    let after = src.chars_from(byte).next();
    work(2);
    match (before, after) {
        (Some((_, a)), Some((_, b))) => breaks_at(src, byte, props(a), props(b)),
        // Only a text shorter than it says gets here.
        _ => true,
    }
}

fn next_boundary_of<S: Source + ?Sized>(src: &S, byte: usize) -> Option<usize> {
    let len = src.len();
    if byte >= len {
        return None;
    }
    // Every candidate is the end of a char, and the first char's end is
    // past `byte`.
    let mut chars = src.chars_from(src.floor_char_boundary(byte));
    let (_, first) = chars.next()?;
    work(1);
    let mut a = props(first);
    // The state before the current candidate, once a rule has needed it.
    let mut state: Option<State> = None;
    for (at, c) in chars {
        work(1);
        let b = props(c);
        let joins = match pair(a, b) {
            Pair::Break => false,
            Pair::Join => true,
            Pair::Context => {
                let known = *state.get_or_insert_with(|| state_at(src, at));
                context_joins(known, a, b)
            }
        };
        if !joins {
            return Some(at);
        }
        state = state.map(|known| step(known, b));
        a = b;
    }
    Some(len)
}

fn prev_boundary_of<S: Source + ?Sized>(src: &S, byte: usize) -> Option<usize> {
    let len = src.len();
    if byte == 0 {
        return None;
    }
    if byte > len {
        return Some(len);
    }
    // The candidates are the char boundaries before `byte`, from the
    // nearest one back; `at` is inside the text, so a char starts there.
    let mut at = src.floor_char_boundary(byte - 1);
    let Some((_, first)) = src.chars_from(at).next() else {
        return Some(at);
    };
    work(1);
    let mut b = props(first);
    for (start, c) in src.chars_before(at) {
        work(1);
        let a = props(c);
        if breaks_at(src, at, a, b) {
            return Some(at);
        }
        at = start;
        b = a;
    }
    Some(0)
}

/// The forward iteration shared by [`StrGraphemes`] and [`Graphemes`]:
/// the spans between consecutive boundaries of the chars `chars` yields,
/// which end at `end`.
#[derive(Clone)]
struct Segmenter<I> {
    chars: I,
    /// The offset and properties of the first char of the next span, once
    /// read.
    next: Option<(usize, u8)>,
    /// The state before that char, once known: from the start, at the start
    /// of the text; otherwise from the first context rule that needs it.
    state: Option<State>,
    end: usize,
}

impl<I: Iterator<Item = (usize, char)>> Segmenter<I> {
    /// Starts before the first char of `chars`, with `state` the state
    /// before it if known.
    fn new(mut chars: I, state: Option<State>, end: usize) -> Self {
        let next = chars.next().map(|(at, c)| {
            work(1);
            (at, props(c))
        });
        Self {
            chars,
            next,
            state,
            end,
        }
    }

    /// The next span. `src` is the text the chars come from; the state is
    /// recovered from it if a context rule needs the state and it is not
    /// yet known.
    fn next_span<S: Source + ?Sized>(&mut self, src: &S) -> Option<Range<usize>> {
        let (start, mut a) = self.next.take()?;
        self.state = self.state.map(|known| step(known, a));
        for (at, c) in self.chars.by_ref() {
            work(1);
            let b = props(c);
            let joins = match pair(a, b) {
                Pair::Break => false,
                Pair::Join => true,
                Pair::Context => {
                    let known = *self.state.get_or_insert_with(|| state_at(src, at));
                    context_joins(known, a, b)
                }
            };
            if !joins {
                self.next = Some((at, b));
                return Some(start..at);
            }
            self.state = self.state.map(|known| step(known, b));
            a = b;
        }
        Some(start..self.end)
    }
}

