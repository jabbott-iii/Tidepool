/// The packed properties of a char, one byte: bits 0-3 are its
/// `Grapheme_Cluster_Break` value (0 is Other), bits 4-5 its
/// `Indic_Conjunct_Break` value (0 is None) and bit 6 whether it is
/// `Extended_Pictographic`. The generated table names these constants.
pub(crate) mod class {
    /// The bits of the `Grapheme_Cluster_Break` value.
    pub(crate) const GCB_MASK: u8 = 0x0F;
    /// GCB=CR.
    pub(crate) const CR: u8 = 1;
    /// GCB=LF.
    pub(crate) const LF: u8 = 2;
    /// GCB=Control.
    pub(crate) const CONTROL: u8 = 3;
    /// GCB=Extend.
    pub(crate) const EXTEND: u8 = 4;
    /// GCB=ZWJ.
    pub(crate) const ZWJ: u8 = 5;
    /// GCB=Regional_Indicator.
    pub(crate) const REGIONAL_INDICATOR: u8 = 6;
    /// GCB=Prepend.
    pub(crate) const PREPEND: u8 = 7;
    /// GCB=SpacingMark.
    pub(crate) const SPACING_MARK: u8 = 8;
    /// GCB=L (Hangul leading jamo).
    pub(crate) const L: u8 = 9;
    /// GCB=V (Hangul vowel jamo).
    pub(crate) const V: u8 = 10;
    /// GCB=T (Hangul trailing jamo).
    pub(crate) const T: u8 = 11;
    /// GCB=LV (Hangul LV syllable).
    pub(crate) const LV: u8 = 12;
    /// GCB=LVT (Hangul LVT syllable).
    pub(crate) const LVT: u8 = 13;
    /// The bits of the `Indic_Conjunct_Break` value.
    pub(crate) const INCB_MASK: u8 = 0x30;
    /// InCB=Linker.
    pub(crate) const INCB_LINKER: u8 = 0x10;
    /// InCB=Consonant.
    pub(crate) const INCB_CONSONANT: u8 = 0x20;
    /// InCB=Extend.
    pub(crate) const INCB_EXTEND: u8 = 0x30;
    /// Extended_Pictographic=Yes.
    pub(crate) const EXT_PICT: u8 = 0x40;
}

// ---------------------------------------------------------------------------
// Properties.

/// The packed properties of `c`. ASCII takes a fast path, which a test
/// checks against the table.
fn props(c: char) -> u8 {
    match c {
        '\n' => LF,
        '\r' => CR,
        '\0'..='\u{1F}' | '\u{7F}' => CONTROL,
        ' '..='~' => 0,
        _ => lookup(c),
    }
}

/// The packed properties of `c` from the table: a binary search over its
/// sorted, disjoint ranges; a code point in none of them has all defaults.
fn lookup(c: char) -> u8 {
    let cp = u32::from(c);
    let found = tables::RANGES.binary_search_by(|&(first, last, _)| {
        if last < cp {
            Ordering::Less
        } else if first > cp {
            Ordering::Greater
        } else {
            Ordering::Equal
        }
    });
    match found {
        Ok(index) => tables::RANGES.get(index).map_or(0, |&(_, _, props)| props),
        Err(_) => 0,
    }
}

const fn gcb(props: u8) -> u8 {
    props & GCB_MASK
}

const fn incb(props: u8) -> u8 {
    props & INCB_MASK
}

const fn ext_pict(props: u8) -> bool {
    props & EXT_PICT != 0
}

