// The API on `&str`.

/// Whether `byte` is an extended grapheme cluster boundary of `text`: false
/// off a char boundary or past the end; 0 and `text.len()` are boundaries,
/// also of the empty text.
pub fn is_boundary(text: &str, byte: usize) -> bool {
    is_boundary_of(text, byte)
}

/// The smallest boundary of `text` greater than `byte`, or `None` if `byte
/// >= text.len()`. Defined for any `byte`, also inside a char.
pub fn next_boundary(text: &str, byte: usize) -> Option<usize> {
    next_boundary_of(text, byte)
}

/// The largest boundary of `text` less than `byte`: `None` if `byte` is 0,
/// and `Some(text.len())` if `byte` is past the end. Defined for any
/// `byte`, also inside a char.
pub fn prev_boundary(text: &str, byte: usize) -> Option<usize> {
    prev_boundary_of(text, byte)
}

/// The extended grapheme clusters of `text`, from the front. The empty text
/// has none. O(1) per char.
pub fn graphemes(text: &str) -> StrGraphemes<'_> {
    StrGraphemes {
        text,
        inner: Segmenter::new(text.char_indices(), Some(START), text.len()),
    }
}

/// The extended grapheme clusters of a `&str`, from the front. Made by
/// [`graphemes`].
#[derive(Clone)]
pub struct StrGraphemes<'a> {
    text: &'a str,
    inner: Segmenter<std::str::CharIndices<'a>>,
}

impl<'a> Iterator for StrGraphemes<'a> {
    type Item = &'a str;

    fn next(&mut self) -> Option<&'a str> {
        let span = self.inner.next_span(self.text)?;
        self.text.get(span)
    }
}

impl FusedIterator for StrGraphemes<'_> {}

// ---------------------------------------------------------------------------
// The API on `Rope`.

impl Rope {
    /// Whether `byte` is an extended grapheme cluster boundary: false off a
    /// char boundary or past the end; 0 and `len` are boundaries, also of
    /// the empty rope. See [`grapheme`](crate::pos::grapheme) for the cost.
    pub fn is_grapheme_boundary(&self, byte: usize) -> bool {
        is_boundary_of(self, byte)
    }

    /// The smallest grapheme cluster boundary greater than `byte`, or `None`
    /// if `byte >= len`. Defined for any `byte`, also inside a char.
    pub fn next_grapheme_boundary(&self, byte: usize) -> Option<usize> {
        next_boundary_of(self, byte)
    }

    /// The largest grapheme cluster boundary less than `byte`: `None` if
    /// `byte` is 0, and `Some(len)` if `byte` is past the end. Defined for
    /// any `byte`, also inside a char.
    pub fn prev_grapheme_boundary(&self, byte: usize) -> Option<usize> {
        prev_boundary_of(self, byte)
    }

    /// The grapheme clusters inside `range`, as byte ranges, from the front:
    /// the spans between consecutive boundaries of the whole text that lie
    /// inside `range`, with the range's two ends as cuts. So the first span
    /// starts at `range.start` and the last ends at `range.end`, even inside
    /// a cluster; an empty range has none.
    ///
    /// O(log n) to make, then O(1) per char. If `range.start` is not 0, the
    /// first time a context rule (GB9c, GB11 or GB12/13) applies inside the
    /// range, the iterator also steps back once from there, as a query does
    /// (see [`grapheme`](crate::pos::grapheme) for that cost). So a window
    /// inside a run of extending marks costs only the window.
    ///
    /// # Errors
    ///
    /// As for [`remove`](Rope::remove).
    pub fn graphemes_in(&self, range: Range<usize>) -> Result<Graphemes<'_>, TextError> {
        let chars = self.char_indices_in(range.clone())?;
        // The state is known at the start of the text; anywhere else it is
        // recovered only if a context rule needs it.
        let state = (range.start == 0).then_some(START);
        Ok(Graphemes {
            rope: self,
            inner: Segmenter::new(chars, state, range.end),
        })
    }
}

/// The extended grapheme clusters of a byte range of a rope, as byte ranges
/// from the start of the rope, from the front. Made by
/// [`Rope::graphemes_in`].
#[derive(Clone)]
pub struct Graphemes<'a> {
    rope: &'a Rope,
    inner: Segmenter<CharIndices<'a>>,
}

impl Iterator for Graphemes<'_> {
    type Item = Range<usize>;

    fn next(&mut self) -> Option<Range<usize>> {
        self.inner.next_span(self.rope)
    }
}

impl FusedIterator for Graphemes<'_> {}
